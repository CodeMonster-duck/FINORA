function monthDay(monthsAgo: number, dayOfMonth: number, ref: Date = new Date()): string {
  const targetMonth = subMonths(ref, monthsAgo);
  const maxDay = new Date(
    targetMonth.getFullYear(),
    targetMonth.getMonth() + 1,
    0,
  ).getDate();
  const clampedDay = Math.min(dayOfMonth, maxDay);
  const clampedToday =
    monthsAgo === 0 ? Math.min(clampedDay, ref.getDate()) : clampedDay;
  return format(setDate(targetMonth, clampedToday), 'yyyy-MM-dd');
}

function isoStamp(dateStr: string): string {
  return `${dateStr}T10:30:00.000Z`;
}

